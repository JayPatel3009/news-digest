import type { Digest } from '../domain/index';

/**
 * Formats a Digest into clean, readable Markdown text suitable for
 * sharing via email, Slack, or note-taking apps.
 * 
 * @param digest - The complete Digest object.
 * @param dateStr - Human-readable date string.
 * @returns Formatted Markdown string.
 */
export function formatBriefingMarkdown(digest: Digest, dateStr: string): string {
  const lines: string[] = [];

  lines.push(`# THE DAILY DIGEST — ${dateStr.toUpperCase()}`);
  lines.push('');
  lines.push('## Executive Summary');
  lines.push(digest.executiveSummary);
  lines.push('');
  lines.push('## Top Stories');

  digest.items.forEach((item, index) => {
    lines.push(`### ${index + 1}. [${item.article.title}](${item.article.url})`);
    lines.push(`**Source:** ${item.article.sourceName} | **Score:** ${item.relevanceScore}%`);
    if (item.article.description) {
      lines.push(`> ${item.article.description}`);
    }
    lines.push(`*AI Insight:* ${item.aiReason}`);
    lines.push('');
  });

  lines.push('---');
  lines.push('_Generated by AI News Digest with Gemini 2.5 Flash Lite_');

  return lines.join('\n');
}

/**
 * Copies the formatted briefing Markdown to the system clipboard.
 * 
 * @param digest - The digest to copy.
 * @param dateStr - Formatted date string.
 * @returns Promise resolving to true if copied successfully, false otherwise.
 */
export async function copyBriefingToClipboard(digest: Digest, dateStr: string): Promise<boolean> {
  if (typeof navigator === 'undefined' || !navigator.clipboard) {
    return false;
  }
  try {
    const text = formatBriefingMarkdown(digest, dateStr);
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}

/**
 * Shares the briefing via the native Web Share API if supported.
 * Falls back to clipboard copy if navigator.share is unavailable.
 * 
 * @param digest - The digest to share.
 * @param dateStr - Formatted date string.
 * @returns Promise resolving to true if shared or copied.
 */
export async function shareBriefing(digest: Digest, dateStr: string): Promise<boolean> {
  if (typeof navigator !== 'undefined' && typeof navigator.share === 'function') {
    try {
      await navigator.share({
        title: `The Daily Digest — ${dateStr}`,
        text: `${digest.executiveSummary}\n\nTop Story: ${digest.items[0]?.article.title ?? ''}`,
      });
      return true;
    } catch (err: unknown) {
      // User cancelled share dialog
      if (err instanceof Error && err.name === 'AbortError') {
        return false;
      }
    }
  }

  // Fallback to clipboard
  return copyBriefingToClipboard(digest, dateStr);
}
